package ru.vedal.portal.assistant;

/**
 * Превращение текста в вектор.
 *
 * <p><b>Зачем интерфейс.</b> Ровно затем же, зачем он у {@link ChatModel}:
 * за ним сеть, деньги и чужая доступность — то есть всё, чего в тесте быть
 * не должно. Нарезка текста, запись в индекс и поиск по близости проверяются
 * подставной моделью, а настоящий HTTP — отдельно, поднятым на месте
 * сервером.
 *
 * <p><b>Почему два метода, а не один.</b> Модели поиска обучены парами:
 * документ кодируется одной моделью, вопрос — другой, и векторы получаются
 * в одном пространстве именно потому, что модели разные. У Яндекса это
 * {@code text-search-doc} и {@code text-search-query}. Закодировать вопрос
 * «документной» моделью можно, и она даже что-то вернёт — просто расстояния
 * перестанут значить то, что должны, а отказа не будет никакого.
 */
public interface Embeddings {

    /**
     * Длина вектора.
     *
     * <p>Она же прошита в типе колонки {@code knowledge_chunk.embedding}:
     * pgvector требует размерность, иначе колонку нельзя проиндексировать.
     * Портал сверяет с этим числом то, что пришло от модели, — расхождение
     * должно быть отказом, а не векторами, которые молча не ищутся.
     */
    int dimension();

    /**
     * Как называется модель. Пишется в {@code knowledge_chunk.model}:
     * векторы разных моделей несравнимы, и отставший чанк надо уметь
     * увидеть, а не искать причину, почему поиск стал хуже.
     */
    String name();

    /** Вектор фрагмента документа — для индексации. */
    float[] ofDocument(String text);

    /** Вектор вопроса — для поиска. */
    float[] ofQuery(String text);
}
