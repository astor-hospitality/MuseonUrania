package ru.vedal.portal.assistant;

/**
 * Озвучивание текста: порт, за которым стоит провайдер.
 *
 * <p>Контракт один на всех: текст на входе, на выходе — готовый к
 * проигрыванию WAV (RIFF, PCM 16 бит, моно). Частота дискретизации у
 * провайдеров разная (16 кГц у Яндекса, 24 или 8 кГц у Сбера — по голосу),
 * но она записана в заголовке, и проигрывателю этого достаточно.
 * Дверь {@code /voice/synthesize} отдаёт {@code audio/wav} при любом
 * провайдере — контракт API не меняется от настройки.
 *
 * <p>Отказы — {@link org.springframework.web.server.ResponseStatusException}
 * с тем же текстом для посетителя, что и раньше: что именно ответил
 * провайдер, наружу не уходит.
 */
public interface TextToSpeech {

    /** Настроен ли провайдер: без ключа дверь отвечает 503, а не падает. */
    boolean available();

    /** WAV с озвученным текстом. Текст уже проверен контроллером на длину. */
    byte[] synthesize(String text);
}
