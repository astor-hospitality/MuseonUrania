package ru.vedal.portal.assistant;

import java.util.List;

/**
 * Кто находит материалы для ответа.
 *
 * <p><b>Зачем отдельный порт.</b> В ответе Ведалины две разные работы:
 * найти материалы и связать их словами. Вторую делает модель, первую —
 * портал, и подменять первую нельзя ни при каких обстоятельствах: у модели
 * нет доступа ни к каталогу, ни к правам на документы, а «вспомнить»
 * изделие она может любое, включая несуществующее.
 *
 * <p>За этим портом сегодня стоят две реализации, и обе честные:
 *
 * <table>
 *   <tr><td>{@link DeterministicSearch}</td>
 *       <td>поиск по словам в названиях и описаниях</td></tr>
 *   <tr><td>{@link VectorSearch}</td>
 *       <td>поиск по близости в индексе pgvector</td></tr>
 * </table>
 *
 * <p><b>Почему смена реализации не трогает ответ.</b> {@link ModelEngine}
 * получает от порта список выдержек и не спрашивает, откуда они. Промпт,
 * нумерация источников, разговор и виджет остаются теми же — векторный поиск
 * меняет только то, ЧТО найдено, а не то, как это показано.
 *
 * <p>Пустой список — штатный исход, а не ошибка: правило проекта «нет
 * опубликованных материалов — нет ответа» сильнее желания что-нибудь
 * сказать. Разговор в этом случае уходит человеку.
 */
public interface Retrieval {

    /**
     * Найденный материал: ссылка на него и то, что о нём написано.
     *
     * @param source куда вести читателя — это и есть ссылка в ответе;
     * @param text   опубликованный текст материала. Ровно он и попадает
     *               в контекст модели: всё, чего здесь нет, для неё
     *               не существует.
     */
    record Passage(LlmEngine.Source source, String text) {}

    /**
     * Что нашлось по вопросу в пределах области.
     *
     * <p>Порядок значим: он же становится порядком источников под ответом
     * и нумерацией сносок в тексте. Первым идёт самое подходящее.
     */
    List<Passage> find(String question, LlmEngine.Scope scope);
}
