// Яндекс Метрика: номер счётчика и отправка целей.
//
// ————— почему номер живёт в переменной окружения —————
//
// Счётчик — не свойство кода, а свойство площадки. У боевого сайта он свой,
// у стенда его быть не должно вовсе: стенд открывают разработчик и заказчик,
// и их визиты в отчётах боевого сайта — это испорченная статистика, а не
// «немного лишних данных». Вписанный в код номер уехал бы на обе площадки.
//
// Пусто — счётчик не подключается, и это НОРМАЛЬНОЕ состояние, а не поломка.
// Так работает машина разработчика, так работает стенд, и так же работает
// боевой сайт до тех пор, пока заказчик не подтвердит вопрос 12.11 PROJECT.md
// и не пришлёт номер. Сайт при этом целый: страницы, формы и Ведалина
// не зависят от аналитики ни одной строкой.
//
// NEXT_PUBLIC_ — потому что счётчик работает в браузере, и Next подставляет
// значение в клиентский код на сборке. Секрета здесь нет: номер счётчика
// виден в разметке любого сайта с Метрикой.

const RAW = (process.env.NEXT_PUBLIC_YANDEX_METRIKA_ID ?? "").trim();

/**
 * Номер счётчика или `null`, если он не задан.
 *
 * Только цифры: Метрика ждёт числовой идентификатор, и опечатка вида
 * «CID-12345» дала бы молчащий счётчик — tag.js не ругается, он просто
 * не отправляет ничего. Пустая строка и мусор здесь одинаково означают
 * «счётчика нет», и разница только в том, что мусор стоит заметить.
 */
export const metrikaId: string | null = /^\d+$/.test(RAW) ? RAW : null;

if (RAW && !metrikaId && typeof console !== "undefined") {
  console.warn(
    `NEXT_PUBLIC_YANDEX_METRIKA_ID должен быть числом, получено «${RAW}». Счётчик не подключён.`,
  );
}

/** Очередь вызовов Метрики. Заводится до загрузки tag.js — см. {@link installMetrika}. */
type Ym = {
  (...args: unknown[]): void;
  a?: unknown[][];
  l?: number;
};

type YmWindow = Window & { ym?: Ym };

const TAG_SRC = "https://mc.yandex.ru/metrika/tag.js";

/**
 * Заводит `window.ym` и загружает tag.js.
 *
 * Заглушка `ym` со своей очередью — это официальный сниппет Метрики,
 * переписанный из строки в модуль. Смысл его в том, что вызовы, сделанные
 * до загрузки tag.js, не теряются: они копятся в `ym.a`, и загруженный
 * скрипт разбирает очередь. Без заглушки первый же `init` упал бы
 * на `ym is not a function`.
 *
 * Переписан он не ради красоты. Сниппет от Яндекса — это `<script>` прямо
 * в разметке, а строгая политика безопасности сайта (`script-src 'self'`)
 * такой скрипт не выполняет. Тот же код, приехавший в бандле, — это 'self'.
 *
 * Вызов повторно безопасен: заглушка заводится один раз, тег ищется в DOM
 * по адресу. Это не украшение — в режиме разработки React монтирует
 * компоненты дважды, и без проверки счётчик встал бы два раза.
 */
export function installMetrika(id: string): void {
  if (typeof window === "undefined") return;
  const w = window as YmWindow;

  if (!w.ym) {
    const ym: Ym = (...args: unknown[]) => {
      (ym.a = ym.a || []).push(args);
    };
    ym.l = Date.now();
    w.ym = ym;
  }

  w.ym(id, "init", {
    // Клики по ссылкам и карта кликов — то, ради чего Метрику и ставят.
    clickmap: true,
    trackLinks: true,
    accurateTrackBounce: true,
    // Согласие v2 прямо включает запись действий. Формы и чат скрыты
    // классом ym-hide-content; запись содержимого полей выключена в счётчике.
    webvisor: true,
  });

  if (!document.querySelector(`script[src="${TAG_SRC}"]`)) {
    const tag = document.createElement("script");
    tag.async = true;
    tag.src = TAG_SRC;
    document.head.appendChild(tag);
  }
}

/**
 * Цель из чек-листа приёмки — в Метрику.
 *
 * Молчит, если счётчика нет или согласие не дано: `window.ym` в этом случае
 * не заведён вовсе. Проверка здесь, а не у каждого места вызова, — иначе
 * каждая кнопка сайта знала бы про аналитику.
 */
export function reachGoal(goal: string): void {
  if (!metrikaId || typeof window === "undefined") return;
  const ym = (window as YmWindow).ym;
  if (typeof ym !== "function") return;
  ym(metrikaId, "reachGoal", goal);
}

/**
 * Просмотр страницы при переходе внутри сайта.
 *
 * Next меняет страницы без перезагрузки, и Метрика об этом не узнаёт сама:
 * `init` считает только ту страницу, на которой счётчик загрузился. Без
 * этого вызова в отчётах остались бы одни точки входа, а весь путь
 * посетителя по сайту пропал бы.
 */
export function trackPageView(url: string): void {
  if (!metrikaId || typeof window === "undefined") return;
  const ym = (window as YmWindow).ym;
  if (typeof ym !== "function") return;
  ym(metrikaId, "hit", url);
}
