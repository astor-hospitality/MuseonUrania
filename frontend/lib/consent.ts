// Согласие посетителя на сторонние ресурсы Яндекса.
//
// Одно хранилище на всех: плашка (`CookieNotice`) спрашивает, счётчик
// (`Analytics`) и карта на контактах (`VedalMapEmbed`) смотрят на ответ.
// Держать это в компоненте нельзя — они в разных ветках дерева, и «принять»
// должно гасить плашку, поднимать счётчик и показывать карту одновременно,
// без перезагрузки страницы.
//
// Вопрос один на оба ресурса, а не два вопроса подряд. Отвечает человек
// на одно и то же: уйдут ли данные о его визите в Яндекс. Разбивать это
// на «счётчик отдельно, карта отдельно» значило бы спрашивать дважды об
// одном, а плашка с двумя вопросами читается ещё хуже, чем с одним.
//
// ————— почему localStorage, а не cookie —————
//
// Для плашки про cookie звучит смешно, но так честнее: cookie уезжает
// на сервер с каждым запросом, localStorage не уезжает никуда. Спросить
// разрешение и в ответ на согласие завести лишнюю передачу данных —
// плохая шутка.

import { metrikaId } from "./analytics";
import { mapEmbedded } from "./maps";

/**
 * Есть ли на площадке хоть один сторонний ресурс — значит, есть о чём
 * спрашивать.
 *
 * Счётчик зависит от номера в окружении, карта стоит на контактах всегда.
 * Пока верно любое из двух, плашка спрашивает; неверны оба — она сообщает,
 * и выбор в ней был бы бутафорией.
 */
export const asksThirdParty = metrikaId !== null || mapEmbedded;

/**
 * Ответ на плашку «cookie нужны, чтобы страницы работали».
 *
 * Остался с той поры, когда счётчиков не было и спрашивать было не о чем:
 * плашка только сообщала. Ключ сохранён, чтобы не показывать её заново
 * тем, кто уже нажал «Понятно», — но ответом на вопрос про аналитику
 * он НЕ считается, см. {@link readConsent}.
 */
const NOTICE_KEY = "vedal.cookies.v1";

/**
 * Ответ на вопрос про сторонние ресурсы Яндекса: `granted` или `denied`.
 *
 * При включённой Метрике v2 спрашивает согласие на Вебвизор заново:
 * прежняя редакция прямо обещала, что запись действий выключена.
 * Для площадки только с картой вопрос не менялся.
 */
const ANALYTICS_KEY = metrikaId ? "vedal.analytics.v2" : "vedal.analytics.v1";

export type Consent =
  /** Ответ ещё не прочитан: серверная отрисовка или недоступное хранилище. */
  | "unknown"
  /** Не спрашивали или спрашивали о другом — плашку показываем. */
  | "unanswered"
  /** Ответил: только необходимые. Ни счётчика, ни карты. */
  | "necessary"
  /**
   * Ответил: сторонние ресурсы Яндекса разрешены. Счётчик подключается,
   * карта на контактах загружается.
   */
  | "analytics";

const SERVER: Consent = "unknown";

// Событие `storage` в своей же вкладке не срабатывает, поэтому подписчиков
// зовём сами. Иначе нажатие на кнопку не убрало бы плашку.
const listeners = new Set<() => void>();

export function subscribe(onChange: () => void): () => void {
  listeners.add(onChange);
  window.addEventListener("storage", onChange);
  return () => {
    listeners.delete(onChange);
    window.removeEventListener("storage", onChange);
  };
}

export function readConsent(): Consent {
  let notice: string | null;
  let analytics: string | null;
  try {
    notice = localStorage.getItem(NOTICE_KEY);
    analytics = localStorage.getItem(ANALYTICS_KEY);
    if (!analytics && metrikaId && localStorage.getItem("vedal.analytics.v1") === "denied") {
      analytics = "denied";
    }
  } catch {
    // Приватный режим или заблокированное хранилище: ответ сохранить некуда,
    // и плашка возвращалась бы на каждой странице. Раздражать этим хуже,
    // чем не спросить про cookie, без которых сайт не работает. Счётчик при
    // таком ответе тоже не поднимается — молчание согласием не считается.
    return SERVER;
  }

  // Сторонних ресурсов нет — вопроса нет. Плашка только сообщает,
  // и старого «Понятно» для неё достаточно.
  if (!asksThirdParty) return notice ? "necessary" : "unanswered";

  // Есть что разрешать — засчитывается только явный ответ.
  // Тот, кто в своё время нажал «Понятно» на плашке без выбора, ответил
  // на другой вопрос: тогда передавать было нечего и некому.
  if (analytics === "granted") return "analytics";
  if (analytics === "denied") return "necessary";
  return "unanswered";
}

/** Серверный снимок: на сервере хранилища нет, и ответ неизвестен. */
export const readServerConsent = (): Consent => SERVER;

function save(entries: [string, string][]): void {
  try {
    for (const [key, value] of entries) localStorage.setItem(key, value);
  } catch {
    // Сюда не попадаем: при недоступном хранилище плашки нет вовсе.
  }
  listeners.forEach((notify) => notify());
}

/**
 * Ответ на вопрос про сторонние ресурсы Яндекса.
 *
 * Пишутся оба ключа: `granted`/`denied` — сам ответ, `vedal.cookies.v1` —
 * отметка «плашку видел». Второй нужен на случай, если сторонние ресурсы
 * потом снимут: плашка не должна вернуться к тому, кто уже всё сказал.
 */
export function answer(allowThirdParty: boolean): void {
  save([
    [NOTICE_KEY, new Date().toISOString()],
    [ANALYTICS_KEY, allowThirdParty ? "granted" : "denied"],
  ]);
}

/**
 * «Понятно» на плашке без выбора — там, где сторонних ресурсов нет.
 *
 * Ключ ответа НЕ пишется, и это главное в этой функции. Записать сюда
 * `granted` значило бы включить счётчик и карту тому, кого о них не
 * спрашивали, — согласие задним числом. Записать `denied` — отказ задним
 * числом, столь же выдуманный. Поэтому появится сторонний ресурс —
 * появится и вопрос, а этот человек увидит плашку ещё раз.
 */
export function acknowledge(): void {
  save([[NOTICE_KEY, new Date().toISOString()]]);
}
