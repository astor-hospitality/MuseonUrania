import type { NextConfig } from "next";
import { loadEnvConfig } from "@next/env";
import { metrikaReplayRoutes, securityHeaders } from "./lib/security-headers";

// Next читает этот файл раньше, чем подхватывает .env.local, поэтому без
// явной загрузки process.env здесь пуст: список разрешённых хостов вышел бы
// пустым, а оптимизатор картинок отвечал бы 400 на каждое фото из хранилища.
// Ошибка тихая — в консоли сборки её не видно, видно только сломанные
// картинки в браузере.
loadEnvConfig(process.cwd());

const mediaUrl = (() => {
  const raw = process.env.NEXT_PUBLIC_MEDIA_URL;
  if (!raw) return null;
  try {
    return new URL(raw);
  } catch {
    // Кривой адрес роняем на сборке, а не на первой картинке у посетителя.
    throw new Error(`NEXT_PUBLIC_MEDIA_URL не разбирается как адрес: ${raw}`);
  }
})();

// next/image не берёт чужой хост молча — иначе сайт стал бы бесплатным
// оптимизатором чужих картинок. Разрешаем ровно тот адрес, что задан
// в NEXT_PUBLIC_MEDIA_URL, и ровно тот путь внутри него.
const remotePatterns = mediaUrl
  ? [
      {
        protocol: mediaUrl.protocol.replace(":", "") as "http" | "https",
        hostname: mediaUrl.hostname,
        port: mediaUrl.port,
        pathname: `${mediaUrl.pathname.replace(/\/+$/, "")}/**`,
      },
    ]
  : [];

// Next с версии 16 отказывается ходить за картинками на адреса, которые
// резолвятся в локальный IP: так закрывают SSRF, когда адрес картинки
// приходит от пользователя. У нас адрес приходит из нашего же контента,
// и запрет снимается только когда хранилище действительно локальное.
//
// Со стандартными настройками этого больше не случается: MinIO из стека
// убран, а NEXT_PUBLIC_MEDIA_URL по умолчанию пуст — снимки едут из
// public/ и никакого хоста тут нет вовсе. Проверка оставлена для того,
// кто поднимет S3-совместимое хранилище у себя, — она общая и стоит ноль.
// На проде хост внешний, условие ложно, и защита остаётся включённой.
const LOCAL_HOST = /^(localhost|127\.\d+\.\d+\.\d+|\[?::1\]?|0\.0\.0\.0)$/i;
const mediaIsLocal = mediaUrl !== null && LOCAL_HOST.test(mediaUrl.hostname);

// ————— канонический адрес и написания, с которых на него уводят —————
//
// Повод конкретный: в выдаче Google по запросу «ведал» сайт стоял ссылкой
// `vedal-med.ru/contact`, а маршрут на сайте — `/contacts/`. Переход из
// поиска давал страницу «не найдено». Заказчик увидел это раньше нас.
//
// Так выглядит любой адрес, который где-то напечатан, а на сайте не заведён:
// в индексе поисковика, в чужой статье, в презентации, в подписи письма,
// на визитке. Изменить чужую ссылку нельзя — можно только ответить на неё
// правильно. Постоянный редирект (308) говорит и человеку, и поисковику одно
// и то же: содержание вот здесь. Со временем поисковик заменяет старый адрес
// в индексе на канонический сам; 404 он держит в индексе месяцами.
//
// Ключ — канонический адрес со слэшем на конце (`trailingSlash` ниже),
// значение — написания, которые на него уводят. Слэш в написаниях не нужен:
// Next добавляет к правилу «(?:/)?$», и `/contact` с `/contact/` ловятся
// одним и тем же источником.
//
// Откуда взяты написания — три источника, и ни одно не выдумано на глаз:
//
// 1. След в самом репозитории. `/press/` — маршрут первого релиза из
//    docs/frontend/sitemap.md, который «заменён на /news/»; `/partners/` —
//    оттуда же, страница партнёров, вместо неё на `/about/` встало членство
//    в Уральской ТПП. Оба адреса стояли в плане и в docs/PROJECT.md §8.4,
//    то есть могли уехать в письмо или в презентацию.
// 2. `/production/archive` — страница фотоархива, снятая с публикации
//    16 сентября. Она была опубликована, и ссылка на неё могла уйти.
// 3. Транслитерации и английские синонимы разделов. Прежний сайт жил
//    на WordPress (docs/strategy/project_brief.md), а у WordPress-сайтов
//    адреса разделов пишутся именно так: `/o-kompanii`, `/kontakty`,
//    `/about-us`, `/contact-us`. Что из них было заведено у заказчика,
//    мы не знаем — доступа к прежней админке у нас нет, — но цена
//    лишнего правила нулевая, а цена пропущенного видна в выдаче.
//
// Чего здесь намеренно НЕТ:
//
// — `/docs`, `/dokumenty`, `/sertifikaty`. Витрина документов скрыта
//   решением заказчика (`NEXT_PUBLIC_DOCUMENTS_ENABLED`), и `/documents/`
//   сегодня сам отвечает 404. Редирект на 404 не лучше 404.
// — снятые с публикации изделия (`vedal-n1`, `vedal-vp4` и ещё семь из
//   миграции V20). Их вернут одним `update`, если НН подтвердит датащит, —
//   а 308 браузер запоминает навсегда и перекрыл бы вернувшуюся карточку.
const CANONICAL: Record<string, readonly string[]> = {
  "/": ["/home", "/main", "/index", "/glavnaya"],
  "/about/": ["/about-us", "/o-kompanii", "/o-nas", "/company", "/partners"],
  "/production/": ["/proizvodstvo", "/manufacturing", "/production/archive"],
  "/products/": ["/product", "/catalog", "/katalog", "/produkciya", "/produktsiya"],
  "/service/": ["/servis", "/service-request", "/support"],
  "/news/": ["/new", "/novosti", "/press", "/blog"],
  "/contacts/": ["/contact", "/contact-us", "/kontakty", "/kontakti"],
  "/legal/privacy/": [
    // `/legal/` без продолжения — не опечатка, а настоящая дыра: каталог
    // `app/(site)/legal/` есть, страницы в нём нет, и адрес отвечает 404.
    "/legal",
    "/privacy",
    "/privacy-policy",
    "/policy",
    "/politika-konfidencialnosti",
  ],
};

/**
 * Написания разворачиваются в правила Next: одно написание — одно правило.
 *
 * Список выше читается как таблица «куда ведём», а не как перечень
 * тридцати почти одинаковых объектов, в котором опечатка в destination
 * не видна глазом.
 */
const canonicalRedirects = Object.entries(CANONICAL).flatMap(([destination, sources]) =>
  sources.map((source) => ({ source, destination, permanent: true })),
);

const nextConfig: NextConfig = {
  // docs/frontend/sitemap.md задаёт маршруты со слешем на конце: /products/,
  // /production/ и так далее. Без этой опции Next срезает слеш и каждая ссылка
  // в меню отвечает редиректом 308 вместо страницы.
  trailingSlash: true,

  // Заголовки безопасности — на всё, что отдаёт сайт. Исключений нет
  // намеренно: страница без политики — это страница, на которой политика
  // не работает, а какая именно окажется такой, заранее не угадать.
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders(process.env) },
      ...metrikaReplayRoutes.map((source) => ({
        source, headers: securityHeaders(process.env, true),
      })),

      // ————— почему посетитель видел вчерашний сайт —————
      //
      // 16 сентября заказчик прислал утренние снимки, где нет правок,
      // выкаченных накануне: старый порядок пунктов меню, удалённая
      // фотография на «Контактах». К обеду у него же в браузере всё новое.
      // На сервере при этом лежала свежая сборка — измерено curl'ом.
      //
      // Причина в заголовке, который Next ставит предсобранным страницам сам
      // (`server/lib/cache-control.js`): при `revalidate: 300` в lib/api.ts
      // выходит
      //
      //   Cache-Control: s-maxage=300, stale-while-revalidate=31535700
      //
      // `s-maxage` браузер не читает вовсе — это указание общим кэшам.
      // Своего срока свежести у ответа для браузера не остаётся, зато
      // остаётся `stale-while-revalidate` почти на год: он разрешает
      // ЛЮБОМУ кэшу, включая браузерный, отдать протухшую копию сразу,
      // а обновить её в фоне. Ровно это посетитель и видит: первый заход
      // после выкатки показывает вчерашний HTML, второй — сегодняшний.
      //
      // Проверено 16 сентября, что виноват не кто-то впереди: в nginx
      // соседа, который держит домен, нет ни `proxy_cache`, ни `expires`,
      // ни `add_header Cache-Control`, а заголовок приезжает уже от шлюза.
      //
      // Что ставим взамен. HTML обязан спрашивать сервер каждый раз; с ETag
      // это стоит один запрос и ответ 304 без тела. Ровно такой заголовок
      // Next ставит своим же `/sitemap.xml` и `/favicon.ico` — значение
      // не выдумано, а взято из его собственной практики.
      //
      // Почему это не ломает статику. Хэшированные файлы Next
      // (`/_next/static/…`) обязаны кэшироваться год: их имена меняются
      // при каждой сборке, и старое имя больше никогда не запрашивается.
      // Заголовки next.config применяются и к ним тоже — в отличие от
      // редиректов, `/_next` из них не исключается автоматически, —
      // поэтому исключение написано в самом источнике. Оптимизатор
      // картинок (`/_next/image`) попадает под то же исключение и
      // сохраняет свои сроки.
      //
      // Снимки в `public/` (`/photos/…`) правилу подчиняются, и это верно:
      // имена у них постоянные, а содержимое заказчик меняет — файл
      // с тем же именем обязан доезжать до посетителя в тот же день.
      //
      // Next не перетирает заголовок, заданный здесь: `sendRenderResult`
      // ставит свой `Cache-Control` только если ответ ещё без него.
      // Динамические ответы — черновики и 404 перехвата — он всё же
      // перекрывает своим `no-store`, и это строже нашего, то есть верно.
      {
        source: "/:path((?!_next/).*)",
        headers: [{ key: "Cache-Control", value: "public, max-age=0, must-revalidate" }],
      },
    ];
  },

  async redirects() {
    return [
      // ————— один сайт — один адрес —————
      //
      // `www.vedal-med.ru` и `vedal-med.ru` — один и тот же server-блок
      // в nginx соседа с одним сертификатом, и обе формы отвечают 200.
      // Для поисковика это два сайта с одинаковым содержимым, то есть
      // дубли: вес ссылок делится пополам, а в выдачу попадает то одна
      // форма, то другая.
      //
      // docs/operations/domain_cutover_vedal_med_ru.md, шаг 3.2, требует
      // редирект на без-www «стороной сервера». Стороны сервера у нас нет:
      // домен держит чужой nginx, и его конфигурацию мы не правим.
      //
      // Имя домена не вписано: `www\.(?<host>.+)` снимает префикс с любого
      // хоста и возвращает остаток. На стенде, который отвечает по адресу-
      // числу, правило не срабатывает вовсе.
      //
      // ————— условие, без которого правило молчит —————
      //
      // Next смотрит на заголовок `Host` пришедшего запроса. До сайта тот
      // доезжает не всегда: Spring Cloud Gateway по умолчанию подставляет
      // в Host адрес назначения (`site:3000`), а фильтра `PreserveHostHeader`
      // в backend/api-gateway/src/main/resources/application.yaml нет. Пока
      // его нет, правило не срабатывает и ничего не ломает — но и не чинит.
      //
      // Оно стоит здесь потому, что цена ему ноль, а включается оно одной
      // строкой в настройке шлюза; и потому, что там, где сайт отвечает
      // без шлюза, оно работает сразу. Надёжная же починка — редирект
      // в самом nginx: у `www.vedal-med.ru` и `vedal-med.ru` там общий
      // server-блок и общий сертификат, разнести их — три строки.
      // Подробности переданы владельцу машины отдельно.
      //
      // Адрес назначения без слэша на конце намеренно: под `:path*` попадают
      // и файлы (`/photos/a.jpg`), которым слэш дописывать нельзя. Страница
      // доедет за два шага — этот редирект и штатный «добавить слэш».
      {
        source: "/:path*",
        has: [{ type: "host", value: "www\\.(?<host>.+)" }],
        destination: "https://:host/:path*",
        permanent: true,
      },

      // Карточка «VEDAL R1, R2» разделена на две, и её адрес полтора месяца
      // лежал в каталоге, в презентации и в письмах заказчику. Постоянный
      // редирект уводит с него на R1: 404 на месте живой ссылки выглядит как
      // снятое с производства изделие, а не как переименованную страницу.
      { source: "/products/vedal-r1-r2", destination: "/products/vedal-r1/", permanent: true },

      // Устаревшие и очевидные написания разделов — таблица CANONICAL выше.
      ...canonicalRedirects,

      // Языковые адреса уводятся на русский корень, а не отвечают 404.
      //
      // Английские и китайские страницы полтора месяца стояли по адресам
      // /en/… и /zh/…, на них есть ссылки и закладки, и поисковик их знает.
      // Публиковаться они перестали (переводов нет, а полурусская страница
      // хуже честной одноязычной) — и с этого момента каждый такой адрес
      // отвечал «страница не найдена». Постоянный редирект говорит и
      // человеку, и поисковику одно и то же: содержание переехало сюда.
      //
      // Оба правила на язык нужны каждому: «/en/:path*» не ловит голый
      // «/en», а он тоже ходил по ссылкам.
      { source: "/en", destination: "/", permanent: true },
      { source: "/en/:path*", destination: "/", permanent: true },
      { source: "/zh", destination: "/", permanent: true },
      { source: "/zh/:path*", destination: "/", permanent: true },

      // `/ru/…` — единственный языковой префикс, у которого содержание
      // никуда не делось: русская версия стоит в корне (docs/frontend/i18n.md,
      // раздел 2). Поэтому не на главную, а на ту же страницу без префикса:
      // `/ru/products/` → `/products/`.
      //
      // Документ объявляет `/ru/products/` намеренным 404 — «второй адрес
      // с тем же содержимым дубль для поисковика». Довод верный, вывод нет:
      // дубль снимает как раз редирект, а 404 просто теряет пришедшего
      // по такой ссылке. Второе правило не нужно — `:path*` без сегментов
      // ловит и голый `/ru`, и его адрес назначения собирается в `/`.
      { source: "/ru/:path*", destination: "/:path*/", permanent: true },
    ];
  },

  images: {
    remotePatterns,

    // Разрешённые уровни качества для next/image. С Next 16 любое значение
    // вне списка молча заменяется ближайшим разрешённым, а по умолчанию
    // в списке одно 75 — и `quality={90}` у фотографии тихо превращался бы
    // в 75. Фото страниц сжимаются дважды: при подготовке исходника и здесь,
    // при выдаче WebP под ширину окна. На 75 второе сжатие даёт заметную
    // кашу на однотонных стенах цеха и халатах, на 90 её не видно, а вес
    // растёт умеренно — WebP под размер окна всё равно легче исходного JPEG.
    qualities: [75, 90],

    // Локальное хранилище — значит, оптимизатор выключен.
    //
    // Оптимизатор ходит за исходником САМ, со стороны сервера, по тому же
    // адресу, что стоит в разметке. Пока сайт запущен с машины, это работает:
    // localhost:9000 у браузера и у процесса Next — одно и то же место.
    // В контейнере — уже нет: localhost внутри него ведёт в него самого,
    // хранилище стоит в docker-сети под своим именем, и каждая фотография
    // отдаётся пятисотой, хотя по прямой ссылке файл открывается.
    //
    // Разными адресами это не лечится: в разметку уходит один адрес, и он
    // обязан быть тем, который откроет браузер. Поэтому локально картинка
    // едет из хранилища напрямую, без промежуточного запроса с сервера.
    // Проигрыш — нескачанная оптимизация на машине разработчика; в облаке,
    // где хранилище на внешнем домене, оптимизатор достаёт его и работает
    // как обычно.
    ...(mediaIsLocal ? { dangerouslyAllowLocalIP: true, unoptimized: true } : {}),
  },
};

export default nextConfig;
