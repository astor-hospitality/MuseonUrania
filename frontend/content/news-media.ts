// У записи новости в портале одно поле картинки (news_item.image_src).
// В записи новости пока одно поле картинки, поэтому согласованные дополнительные
// файлы подключаются здесь по slug. Когда редакторам понадобится самостоятельно
// собирать галереи, эту связь надо перенести в модель портала и админку.
//
// Сами файлы лежат в бакете медиа под photos/news/<slug>/ и отдаются оттуда
// (lib/media.ts). В репозитории их нет: видео по 8–10 МБ раздували бы git.
// На машине разработчика без NEXT_PUBLIC_MEDIA_URL лента берётся из
// content/news.ts, и эти страницы не открываются вовсе — пути туда не ведут.
//
// Подписи описывают, что видно на кадре, и не называют людей: кто есть кто
// на снимке, в переданных материалах не сказано.

