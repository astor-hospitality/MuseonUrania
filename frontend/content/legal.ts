// §14.5 плана: короткий текст про cookie, ссылка на политику, кнопка согласия.
//
// Текстов три, и выбирает между ними не редактор, а то, что на площадке
// действительно есть: счётчик Метрики (`NEXT_PUBLIC_YANDEX_METRIKA_ID`)
