// с именем, телефоном, почтой и отметкой согласия. Текст написали до того,
// как формы подключили, и он пережил подключение.
//
// Хуже места для устаревшего утверждения не придумать: страница о защите
// персональных данных сообщала посетителю, что его данные никуда не уходят,
// пока они уходили. Правило «не выдумывать» относится и к утверждениям
// о самих себе — поэтому текст политики правится вместе с кодом, который
// он описывает, а не отдельным документом раз в год.
