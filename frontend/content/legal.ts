// причине карта названа отдельной строкой, а не подразумевается словом
// «сервисы»: согласие на то, чего человеку не назвали, согласием не является.
//
// ————— почему два ответа, а не один —————
//
// Cookie самого сайта отклонить нельзя: без них не работают страницы,
// и «отклонить» означало бы «уйти». Метрику и карту отклонить можно: сайт
// без них работает целиком — у карты на месте кадра остаются адрес и ссылка
// «Построить маршрут», — а данные посетителя при них уезжают третьей стороне.
// Поэтому кнопка «Только необходимые» появляется вместе со сторонним ресурсом
// и вместе с ним исчезает.
